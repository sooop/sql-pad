function haystack(item) {
  return [item.title, item.syntax, item.desc, ...item.keywords].join('\n').toLowerCase();
}

/** 검색: query 를 공백으로 나눠 모든 단어가 title/syntax/desc/keywords 중 어딘가에 포함되면 일치한다. 빈 query 는 전체. */
export function searchCheatsheet(query) {
  const words = String(query || '').toLowerCase().split(/\s+/).filter(Boolean);
  const out = [];
  for (const section of CHEATSHEET) {
    for (const item of section.items) {
      const h = haystack(item);
      if (words.every((w) => h.includes(w))) out.push({ section, item });
    }
  }
  return out;
}

/** 커서 아래 단어로 가장 잘 맞는 항목 하나. 없으면 null. 키워드 정확 일치, 키워드 단어 일치, 제목/문법 단어 일치 순으로 점수를 준다. */
export function lookupWord(word) {
  const w = String(word || '').trim().toLowerCase().replace(/\s+/g, ' ');
  if (!w) return null;
  const wordRe = new RegExp('(^|[^a-z0-9_])' + w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '([^a-z0-9_]|$)');
  let best = null;
  let bestScore = 0;
  for (const section of CHEATSHEET) {
    for (const item of section.items) {
      let score = 0;
      if (item.keywords.some((k) => k.toLowerCase() === w)) score = 3;
      else if (item.keywords.some((k) => wordRe.test(k.toLowerCase()))) score = 2;
      else if (wordRe.test((item.title + '\n' + item.syntax).toLowerCase())) score = 1;
      if (score > bestScore) {
        best = item;
        bestScore = score;
      }
    }
  }
  return best;
}
